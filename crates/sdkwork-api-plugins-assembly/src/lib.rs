//! API assembly for sdkwork-plugins.
//! Application bootstrap lives in `bootstrap.rs`; route inventory is in `assembly-manifest.json`.
//! SDKWORK-ASSEMBLY-LIB-CUSTOM: exports beyond the canonical materializer template.

mod bootstrap;
mod generated;

pub use bootstrap::{
    assemble_api_router, assemble_api_router_with_pool, assemble_app_api_contribution,
    assemble_backend_api_contribution, bootstrap_database_from_env, web_module,
    web_module_with_pool, ApiAssembly,
};

/// Total HTTP operations declared by this assembly's route manifests
/// (6 backend-api admin operations + 3 app-api marketplace operations).
///
/// The count is read from the route manifests the assembly mounts, not from a
/// generated constant: `src/generated.rs` is regenerated by
/// `pnpm api:assembly:materialize` and only carries the route-crate inventory.
pub fn assembly_route_count() -> usize {
    sdkwork_routes_plugins_app_api::app_route_manifest()
        .routes()
        .len()
        + sdkwork_routes_plugins_backend_api::backend_route_manifest()
            .routes()
            .len()
}

/// Number of route crates this assembly composes, from the generated route
/// inventory.
pub fn assembly_route_crate_count() -> usize {
    generated::ROUTE_CRATE_COUNT
}
